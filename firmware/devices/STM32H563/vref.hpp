	constexpr auto operator||(opsy::utility::clear_set<vrefbuf_csr_r> other) const -> opsy::utility::clear_set<vrefbuf_csr_r> {return opsy::utility::clear_set<vrefbuf_csr_r>(vrefbuf_csr_r(mask) | other.clear(), *this | other.set()); }

private:
